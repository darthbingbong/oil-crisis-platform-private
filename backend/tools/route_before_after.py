r"""Build docs/m10_route_planning_before_after.md from docs/m10_voyage_before.json and docs/m10_voyage_after.json (see snapshot_voyage_numbers.py)."""

import json
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent.parent / "docs"
B = json.loads((DOCS / "m10_voyage_before.json").read_text(encoding="utf-8"))
A = json.loads((DOCS / "m10_voyage_after.json").read_text(encoding="utf-8"))
PLANS = json.loads((Path(__file__).resolve().parent.parent / "data" / "ais_route_plans.json").read_text(encoding="utf-8"))["plans"]


XCHECK = {"ras_tanura_ningbo": "xcheck_ras_tanura_ningbo_point", "primorsk_rotterdam": "xcheck_primorsk_rotterdam_point"}


def pct(a, b):
    return "" if not a or b is None else f"{(b - a) / a * 100:+.1f}%"


def row(label, a, b, fmt="{:,.0f}"):
    f = lambda v: "n/a" if v is None else fmt.format(v)       # noqa: E731
    return f"| {label} | {f(a)} | {f(b)} | {pct(a, b)} |"


out = ["# M10: real sea distances for the voyage days (before and after)", "",
       "Before = v1.0 (great-circle sum over hand-placed waypoints at 14 knots). After = ShipFinder route planning (planned sea distance) at 14 knots, retrieved 2026-11-02. "
       "Generated by `backend/tools/route_before_after.py` from `docs/m10_voyage_before.json` and `docs/m10_voyage_after.json`, which the application itself produced.", "",
       "## 1. Distances behind the voyage days", "",
       "| Voyage | Used for | Before nm | After nm | Change | Point-to-Point cross-check |", "|---|---|---|---|---|---|"]
for pid, p in PLANS.items():
    if p["service"] != "route_port":
        continue
    q = PLANS.get(XCHECK.get(pid, ""))
    xc = f"{q['distance_nm']:,.0f} nm ({(q['distance_nm'] - p['distance_nm']) / p['distance_nm'] * 100:+.1f}%)" if q else ""
    out.append(f"| {p['note']} | {', '.join(p['replaces'])} | {p['estimate_nm_before']:,.0f} | {p['distance_nm']:,.1f} | {pct(p['estimate_nm_before'], p['distance_nm'])} | {xc} |")
out += ["", "## 2. Voyage days and default detour", "", "| Route | Before (days) | After (days) | Change |", "|---|---|---|---|"]
for rid, a in B["routes"].items():
    b = A["routes"][rid]
    if a["baseline_voyage_days"] or a["default_detour_days"]:
        if a["baseline_voyage_days"]:
            out.append(row(f"{rid}: baseline voyage", a["baseline_voyage_days"], b["baseline_voyage_days"], "{:.1f}"))
        if a["default_detour_days"]:
            out.append(row(f"{rid}: default detour (Cape minus Suez)", a["default_detour_days"], b["default_detour_days"], "{:.1f}"))
out += ["", "## 3. The Suez 20-day detour example (60 days, defaults otherwise), from `POST /api/v1/simulate/report`", "", "| Quantity | Before | After | Change |", "|---|---|---|---|"]
sb, sa = B["cases"]["suez_20d_detour_60d"], A["cases"]["suez_20d_detour_60d"]
for label, key, fmt in [("Baseline voyage T (days)", "baseline_voyage_days", "{:.1f}"), ("Barrels displaced per day", "displaced_bpd", "{:,.0f}"), ("Supply loss (% of world)", "supply_loss_pct", "{:.3f}"),
                        ("Price impact, supply loss / 0.15 (%)", "price_impact_pct", "{:.1f}"), ("EVs required", "evs_required", "{:,.0f}"),
                        ("Extra lithium (t LCE)", "extra_lithium_t_lce", "{:,.0f}"), ("Lithium deficit (t LCE)", "lithium_deficit_t_lce", "{:,.0f}"), ("Transit gap (barrels)", "transit_gap_bbl", "{:,.0f}")]:
    out.append(row(label, sb[key], sa[key], fmt))
out += ["", "## 4. Other cases that depend on the voyage days", "", "| Case | Price impact before | after | Barrels displaced before | after |", "|---|---|---|---|---|"]
for name in B["cases"]:
    if name == "suez_20d_detour_60d":
        continue
    b, a = B["cases"][name], A["cases"][name]
    out.append(f"| {name} | {b['price_impact_pct']:.1f}% | {a['price_impact_pct']:.1f}% | {b['displaced_bpd']:,.0f} | {a['displaced_bpd']:,.0f} |")
out += ["", "Hormuz blockade does not use voyage days, so it is unchanged. Everything else (flows, elasticity, EV and lithium factors) is untouched.", ""]
(DOCS / "m10_route_planning_before_after.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/m10_route_planning_before_after.md")
